"""Banco de cadastro das empresas (CNPJ, nome e token do ERP criptografado).

Na hospedagem usa Postgres: basta a variável DATABASE_URL (o Railway cria ao adicionar o banco). Sem ela, usa o
arquivo SQLite local (desenvolvimento e testes). O resto do app não sabe qual dos dois está por baixo: as consultas
usam '?' como marcador e as linhas se comportam como dicionário nos dois casos.

Ao ligar pela primeira vez com Postgres, os cadastros do arquivo SQLite antigo (volume /data) são copiados
automaticamente, uma única vez (ver _importar_do_sqlite_se_vazio).
"""

import logging
import sqlite3
from contextlib import contextmanager
from pathlib import Path

from app.config import settings

logger = logging.getLogger(__name__)

USANDO_POSTGRES = bool(settings.database_url)

SCHEMA = """
CREATE TABLE IF NOT EXISTS empresas (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    cnpj TEXT UNIQUE NOT NULL,
    nome_fantasia TEXT NOT NULL,
    api_token TEXT NOT NULL,
    ativo INTEGER NOT NULL DEFAULT 1,
    criado_em TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
"""

# Mesmas colunas e formatos do SQLite (criado_em em texto UTC 'AAAA-MM-DD HH:MM:SS'), para a tela do /admin e o
# código não mudarem. O id aceita valor explícito para a cópia inicial manter os mesmos números.
SCHEMA_POSTGRES = """
CREATE TABLE IF NOT EXISTS empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj TEXT UNIQUE NOT NULL,
    nome_fantasia TEXT NOT NULL,
    api_token TEXT NOT NULL,
    ativo INTEGER NOT NULL DEFAULT 1,
    criado_em TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
"""

_pool = None


def _pool_postgres():
    """Conexões reaproveitadas (cada tela consulta o cadastro da empresa; abrir conexão nova toda vez é lento)."""
    global _pool
    if _pool is None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        _pool = ConnectionPool(
            settings.database_url, min_size=1, max_size=5, kwargs={"row_factory": dict_row}, open=True, timeout=15
        )
    return _pool


class _ConexaoPostgres:
    """Aceita as mesmas consultas do SQLite: troca o marcador '?' pelo '%s' do Postgres.
    (Nenhuma consulta do app tem '?' ou '%' literal no texto; se um dia tiver, usar parâmetro.)"""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params=()):
        return self._conn.execute(sql.replace("?", "%s"), params)


def get_connection() -> sqlite3.Connection:
    conn = sqlite3.connect(settings.database_path)
    conn.row_factory = sqlite3.Row
    return conn


@contextmanager
def db_session():
    """Uma transação: grava tudo no fim; se der erro no meio, nada é gravado."""
    if USANDO_POSTGRES:
        with _pool_postgres().connection() as conn:   # o pool confirma no fim ou desfaz se houver erro
            yield _ConexaoPostgres(conn)
        return
    conn = get_connection()
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def init_db() -> None:
    if USANDO_POSTGRES:
        with db_session() as conn:
            conn.execute(SCHEMA_POSTGRES)
            _importar_do_sqlite_se_vazio(conn)
        return
    with get_connection() as conn:
        conn.executescript(SCHEMA)
        # Bancos criados antes da mudança para login com usuário/senha do próprio
        # Meu ERP Online ainda têm essa coluna; login não depende mais dela.
        columns = {row["name"] for row in conn.execute("PRAGMA table_info(empresas)")}
        if "senha_hash" in columns:
            conn.execute("ALTER TABLE empresas DROP COLUMN senha_hash")


def _importar_do_sqlite_se_vazio(conn) -> None:
    """Primeira vez com Postgres: copia os cadastros do arquivo SQLite antigo, se ele existir.

    Só roda com a tabela do Postgres vazia (nunca sobrescreve nada). O token é copiado exatamente como está no
    arquivo (já criptografado): não é aberto nem aparece em log. Tudo numa transação: se a conferência no final
    não bater, nada é gravado e o app não liga (melhor parar do que subir sem os clientes)."""
    conn.execute("LOCK TABLE empresas IN EXCLUSIVE MODE")   # dois processos ligando juntos não copiam em dobro
    if conn.execute("SELECT 1 FROM empresas LIMIT 1").fetchone():
        return
    caminho = Path(settings.database_path)
    if not caminho.is_file():
        logger.warning("Postgres vazio e arquivo SQLite %s não encontrado: começando sem empresas cadastradas.", caminho)
        return
    origem = sqlite3.connect(caminho.resolve().as_uri() + "?mode=ro", uri=True)   # só leitura: o arquivo fica intacto
    try:
        origem.row_factory = sqlite3.Row
        linhas = origem.execute(
            "SELECT id, cnpj, nome_fantasia, api_token, ativo, criado_em FROM empresas ORDER BY id"
        ).fetchall()
    except sqlite3.Error:
        logger.exception("arquivo SQLite %s sem a tabela de empresas: nada copiado", caminho)
        return
    finally:
        origem.close()
    if not linhas:
        return
    for linha in linhas:
        conn.execute(
            "INSERT INTO empresas (id, cnpj, nome_fantasia, api_token, ativo, criado_em) VALUES (?, ?, ?, ?, ?, ?)",
            tuple(linha),
        )
    # Os próximos cadastros continuam a numeração depois do maior id copiado.
    conn.execute("SELECT setval(pg_get_serial_sequence('empresas', 'id'), (SELECT MAX(id) FROM empresas))")

    copiados = {(l["cnpj"], l["api_token"], l["ativo"]) for l in linhas}
    no_postgres = {(l["cnpj"], l["api_token"], l["ativo"]) for l in conn.execute("SELECT cnpj, api_token, ativo FROM empresas")}
    if copiados != no_postgres:
        raise RuntimeError("conferência da cópia SQLite -> Postgres falhou; nada foi gravado")
    logger.warning("%d empresa(s) copiadas do arquivo SQLite (%s) para o Postgres.", len(linhas), caminho)
