"""Tabelas do Prime Vendas (prefixo pv_). Ficam no mesmo banco do PrimeSys Info, mas são só do Vendas:
o Vendas apenas LÊ a tabela de empresas (cadastro e token), nunca altera.

Datas gravadas como texto UTC 'AAAA-MM-DD HH:MM:SS' (igual ao resto do banco), geradas no Python para o mesmo
código valer no Postgres (hospedagem) e no SQLite (testes locais)."""

from datetime import datetime, timezone

from app.database import USANDO_POSTGRES, db_session

_ID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if USANDO_POSTGRES else "INTEGER PRIMARY KEY AUTOINCREMENT"

# Um registro por celular conectado. O app guarda o token; aqui fica só o resumo (hash) dele, então quem
# lê o banco não consegue se passar pelo aparelho. Revogar = desconectar o celular na hora.
SCHEMA = [
    f"""CREATE TABLE IF NOT EXISTS pv_aparelhos (
        id {_ID},
        cnpj TEXT NOT NULL,
        token_hash TEXT NOT NULL UNIQUE,
        id_usuario INTEGER NOT NULL,
        id_funcionario INTEGER NOT NULL,
        nome_vendedor TEXT NOT NULL,
        aparelho TEXT NOT NULL DEFAULT '',
        criado_em TEXT NOT NULL,
        ultimo_uso TEXT NOT NULL,
        conferido_em TEXT NOT NULL,
        revogado INTEGER NOT NULL DEFAULT 0
    )""",
    "CREATE INDEX IF NOT EXISTS pv_aparelhos_cnpj ON pv_aparelhos (cnpj)",
    # Cópia do catálogo de cada empresa (lida do ERP pelo servidor, uma vez para todos os vendedores).
    # 'carimbo' = quando a linha mudou NESTA cópia; o celular pede só o que tem carimbo maior que o último que viu.
    # 'resumo' = hash do conteúdo, para só regravar (e reenviar aos celulares) o que mudou de verdade.
    """CREATE TABLE IF NOT EXISTS pv_produtos (
        cnpj TEXT NOT NULL, id INTEGER NOT NULL, descricao TEXT NOT NULL, barras TEXT NOT NULL DEFAULT '',
        embalagem TEXT NOT NULL DEFAULT '', preco DOUBLE PRECISION, permite_desconto INTEGER NOT NULL DEFAULT 1, desconto_max DOUBLE PRECISION,
        ativo INTEGER NOT NULL DEFAULT 1, resumo TEXT NOT NULL, carimbo TEXT NOT NULL,
        PRIMARY KEY (cnpj, id)
    )""",
    """CREATE TABLE IF NOT EXISTS pv_estoque (
        cnpj TEXT NOT NULL, id INTEGER NOT NULL, saldo DOUBLE PRECISION NOT NULL DEFAULT 0, resumo TEXT NOT NULL, carimbo TEXT NOT NULL,
        PRIMARY KEY (cnpj, id)
    )""",
    """CREATE TABLE IF NOT EXISTS pv_clientes (
        cnpj TEXT NOT NULL, id INTEGER NOT NULL, nome TEXT NOT NULL, fantasia TEXT NOT NULL DEFAULT '', documento TEXT NOT NULL DEFAULT '',
        bairro TEXT NOT NULL DEFAULT '', cidade TEXT NOT NULL DEFAULT '', uf TEXT NOT NULL DEFAULT '', fone TEXT NOT NULL DEFAULT '',
        ativo INTEGER NOT NULL DEFAULT 1, resumo TEXT NOT NULL, carimbo TEXT NOT NULL,
        PRIMARY KEY (cnpj, id)
    )""",
    "CREATE INDEX IF NOT EXISTS pv_produtos_carimbo ON pv_produtos (cnpj, carimbo)",
    "CREATE INDEX IF NOT EXISTS pv_estoque_carimbo ON pv_estoque (cnpj, carimbo)",
    "CREATE INDEX IF NOT EXISTS pv_clientes_carimbo ON pv_clientes (cnpj, carimbo)",
    # Pedidos recebidos dos celulares. id = identificador criado no celular (vai como idExterno no ERP: reenviar não duplica).
    """CREATE TABLE IF NOT EXISTS pv_pedidos (
        id TEXT PRIMARY KEY, cnpj TEXT NOT NULL, id_aparelho INTEGER NOT NULL, id_funcionario INTEGER NOT NULL, tipo TEXT NOT NULL,
        dados TEXT NOT NULL, resumo TEXT NOT NULL DEFAULT '{}', situacao TEXT NOT NULL, mensagem TEXT NOT NULL DEFAULT '',
        id_documento INTEGER, criado_em TEXT NOT NULL, enviado_em TEXT, atualizado_em TEXT NOT NULL, carimbo TEXT NOT NULL
    )""",
    "CREATE INDEX IF NOT EXISTS pv_pedidos_vendedor ON pv_pedidos (cnpj, id_funcionario, carimbo)",
    # Clientes cadastrados pelo app (id criado no celular: reenviar o mesmo cadastro não cria outro cliente).
    """CREATE TABLE IF NOT EXISTS pv_cadastros (
        id TEXT PRIMARY KEY, cnpj TEXT NOT NULL, id_funcionario INTEGER NOT NULL, id_pessoa INTEGER NOT NULL,
        resultado TEXT NOT NULL, criado_em TEXT NOT NULL
    )""",
    # Resultados de consultas ao ERP que mudam pouco (ver vendas/memoria.py): sobrevivem a uma publicação.
    """CREATE TABLE IF NOT EXISTS pv_cache (
        cnpj TEXT NOT NULL, chave TEXT NOT NULL, valor TEXT NOT NULL, ate TEXT NOT NULL,
        PRIMARY KEY (cnpj, chave)
    )""",
    # Controle da leitura do ERP por empresa e tabela: até onde já leu (marca do ERP) e quando.
    """CREATE TABLE IF NOT EXISTS pv_sincronizacao (
        cnpj TEXT NOT NULL, tabela TEXT NOT NULL, marca_erp TEXT NOT NULL DEFAULT '',
        ultima_leitura TEXT NOT NULL DEFAULT '', ultima_completa TEXT NOT NULL DEFAULT '', erro TEXT NOT NULL DEFAULT '',
        PRIMARY KEY (cnpj, tabela)
    )""",
]


def agora_texto() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def carimbo_agora() -> str:
    """Com microssegundos: ordena as gravações da cópia do catálogo (o celular guarda o maior que já recebeu)."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")


def texto_para_data(texto: str) -> datetime:
    return datetime.strptime(texto, "%Y-%m-%d %H:%M:%S").replace(tzinfo=timezone.utc)


# Colunas acrescentadas depois que a tabela já existia na hospedagem (tabela, coluna, definição).
COLUNAS_NOVAS = [
    ("pv_pedidos", "vendas", "TEXT NOT NULL DEFAULT ''"),   # código(s) da venda gerada ao finalizar o pedido
]


def criar_tabelas() -> None:
    with db_session() as conn:
        for comando in SCHEMA:
            conn.execute(comando)
        for tabela, coluna, definicao in COLUNAS_NOVAS:   # nomes fixos, definidos acima
            if USANDO_POSTGRES:
                conn.execute(f"ALTER TABLE {tabela} ADD COLUMN IF NOT EXISTS {coluna} {definicao}")
            elif coluna not in {r["name"] for r in conn.execute(f"PRAGMA table_info({tabela})")}:
                conn.execute(f"ALTER TABLE {tabela} ADD COLUMN {coluna} {definicao}")
